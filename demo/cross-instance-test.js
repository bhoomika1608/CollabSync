/**
 * cross-instance-test.js
 * ─────────────────────────────────────────────────────────────
 * CollabSync — Cross-Instance Redis Pub/Sub Verification Script
 * ─────────────────────────────────────────────────────────────
 *
 * PURPOSE
 * ───────
 * Proves that a Yjs update sent to server:1 (port 3001) reaches a
 * client connected to server:2 (port 3002) — via Redis pub/sub,
 * NOT via a direct connection between the two servers.
 *
 * HOW TO RUN
 * ──────────
 *   # 1. Start the full stack:
 *   docker compose up --build -d
 *
 *   # 2. Wait for health checks to pass (~30 s):
 *   docker compose ps
 *
 *   # 3. Install dependencies and run this script:
 *   cd demo && npm install && node cross-instance-test.js
 *
 * WHAT IS TESTED
 * ──────────────
 *   Test 1  — Basic A→B cross-instance delivery + content verification
 *   Test 2  — Bidirectional (B→A) to confirm both instances relay
 *   Test 3  — 20 rapid updates: all arrive in order, no drops
 *   Test 4  — Latency stats over 50 updates (p50 / p95 / max)
 *   Summary — PASS / FAIL with per-test results
 *
 * WHY CONNECT DIRECTLY TO :3001/:3002 (NOT :80)?
 * ───────────────────────────────────────────────
 * If we connected both clients through nginx (:80), nginx might route
 * both to the SAME backend (same IP → same upstream in round-robin).
 * Connecting directly bypasses nginx and guarantees Client A is on
 * server:1 and Client B is on server:2. Only the Redis adapter can
 * bridge them — proving the pub/sub layer works.
 */

'use strict';

const { io: socketIo } = require('socket.io-client');
const Y = require('yjs');

// ─────────────────────────────────────────────────────────────
// Configuration
// ─────────────────────────────────────────────────────────────

const SERVER_A_URL = process.env.SERVER_A_URL || 'http://localhost:3001';
const SERVER_B_URL = process.env.SERVER_B_URL || 'http://localhost:3002';
const DOC_ID = 'cross-instance-' + Date.now();
const LATENCY_WARN_MS = 100;   // warn if any update exceeds this
const LATENCY_FAIL_MS = 500;   // fail test if p95 exceeds this
const RAPID_UPDATE_COUNT = 20;
const LATENCY_SAMPLE_COUNT = 50;
const TEXT_KEY = 'content';

// ─────────────────────────────────────────────────────────────
// Colour helpers for terminal output
// ─────────────────────────────────────────────────────────────

const c = {
  reset:  '\x1b[0m',
  green:  '\x1b[32m',
  red:    '\x1b[31m',
  yellow: '\x1b[33m',
  cyan:   '\x1b[36m',
  bold:   '\x1b[1m',
  dim:    '\x1b[2m',
};

const pass  = `${c.green}✓${c.reset}`;
const fail  = `${c.red}✗${c.reset}`;
const warn  = `${c.yellow}⚠${c.reset}`;
const arrow = `${c.cyan}→${c.reset}`;

// ─────────────────────────────────────────────────────────────
// Core helpers
// ─────────────────────────────────────────────────────────────

/**
 * Connect a Socket.io client to `url` with WebSocket-only transport.
 *
 * WHY transports: ['websocket']?
 * Without this, Socket.io starts with long-polling and upgrades.
 * Long-polling requires sticky sessions (each poll request must reach
 * the same server instance). Our nginx uses plain round-robin, so
 * long-poll requests could hit different instances and break the sid.
 * WebSocket-only skips polling entirely — one TCP connection, one
 * server, no session fragmentation.
 */
function connect(url, userId, label) {
  return new Promise((resolve, reject) => {
    const socket = socketIo(url, {
      transports: ['websocket'],
      reconnectionAttempts: 3,
    });

    const timeout = setTimeout(() => {
      socket.close();
      reject(new Error(`${label}: connection to ${url} timed out after 10s`));
    }, 10_000);

    socket.on('connect', () => {
      clearTimeout(timeout);
      resolve({ socket, userId, label });
    });

    socket.on('connect_error', (err) => {
      clearTimeout(timeout);
      reject(new Error(`${label}: connect_error → ${err.message}`));
    });
  });
}

/**
 * Join a document and receive the initial full state.
 * Returns a Y.Doc seeded with whatever the server currently has.
 */
function joinDoc(socket, userId, docId) {
  return new Promise((resolve, reject) => {
    const ydoc = new Y.Doc();

    const timeout = setTimeout(() => {
      reject(new Error(`joinDoc timed out for ${userId}`));
    }, 10_000);

    socket.once('doc:load', ({ update }) => {
      clearTimeout(timeout);
      // Seed our local Y.Doc with the server's current state.
      if (update && update.length > 0) {
        Y.applyUpdate(ydoc, Buffer.from(update));
      }
      resolve(ydoc);
    });

    socket.emit('doc:join', {
      docId,
      userId,
      userInfo: { name: userId },
    });
  });
}

/**
 * Encode a text insertion into a Yjs binary update.
 * The update is generated by a fresh Y.Doc so it has a unique clientId —
 * this simulates a real client edit rather than a synthetic blob.
 */
function makeTextUpdate(text) {
  const ydoc = new Y.Doc();
  ydoc.getText(TEXT_KEY).insert(0, text);
  return Y.encodeStateAsUpdate(ydoc);
}

/**
 * Send a Yjs update from `senderSocket` to the server, then wait for
 * `receiverSocket` to get the relayed `doc:update` event.
 * Returns { latencyMs, receivedUpdateBytes }.
 */
function sendAndAwaitRelay(senderSocket, receiverSocket, docId, updateBytes) {
  return new Promise((resolve, reject) => {
    const timeout = setTimeout(() => {
      reject(new Error('Relay timed out after 5 s — is Redis running?'));
    }, 5_000);

    receiverSocket.once('doc:update', ({ update }) => {
      const latencyMs = Date.now() - t0;
      clearTimeout(timeout);
      resolve({ latencyMs, receivedUpdateBytes: Buffer.from(update) });
    });

    const t0 = Date.now();
    senderSocket.emit('doc:update', {
      docId,
      update: Buffer.from(updateBytes),
    });
  });
}

/**
 * Apply a received Yjs update buffer to a Y.Doc and return the text.
 */
function applyAndRead(ydoc, updateBuffer) {
  Y.applyUpdate(ydoc, updateBuffer);
  return ydoc.getText(TEXT_KEY).toString();
}

/**
 * Compute percentile from a sorted array of numbers.
 */
function percentile(sorted, p) {
  const idx = Math.ceil((p / 100) * sorted.length) - 1;
  return sorted[Math.max(0, idx)];
}

// ─────────────────────────────────────────────────────────────
// Test runner
// ─────────────────────────────────────────────────────────────

async function runTests() {
  const results = [];
  let clientA_socket, clientB_socket, ydocA, ydocB;

  console.log(`\n${c.bold}╔══════════════════════════════════════════════════════╗`);
  console.log(`║   CollabSync — Cross-Instance Redis Pub/Sub Test     ║`);
  console.log(`╚══════════════════════════════════════════════════════╝${c.reset}\n`);

  console.log(`  Document ID : ${c.dim}${DOC_ID}${c.reset}`);
  console.log(`  Server A    : ${c.cyan}${SERVER_A_URL}${c.reset} (server:1)`);
  console.log(`  Server B    : ${c.cyan}${SERVER_B_URL}${c.reset} (server:2)\n`);

  // ────────────────────────────────────────────────────────────
  // Setup: connect and join
  // ────────────────────────────────────────────────────────────
  console.log(`${c.bold}[SETUP] Connecting clients to separate instances…${c.reset}`);
  try {
    const connA = await connect(SERVER_A_URL, 'alice', 'Client A');
    clientA_socket = connA.socket;
    console.log(`  ${pass} Client A connected ${arrow} server:1 (${SERVER_A_URL})  [sid: ${clientA_socket.id}]`);

    const connB = await connect(SERVER_B_URL, 'bob', 'Client B');
    clientB_socket = connB.socket;
    console.log(`  ${pass} Client B connected ${arrow} server:2 (${SERVER_B_URL})  [sid: ${clientB_socket.id}]`);

    ydocA = await joinDoc(clientA_socket, 'alice', DOC_ID);
    ydocB = await joinDoc(clientB_socket, 'bob',   DOC_ID);
    console.log(`  ${pass} Both clients joined document "${DOC_ID}"\n`);
  } catch (err) {
    console.error(`\n  ${fail} ${c.red}Setup failed: ${err.message}${c.reset}`);
    console.error(`\n  ${warn} Make sure all services are healthy:`);
    console.error(`       docker compose ps\n`);
    process.exit(1);
  }

  // ────────────────────────────────────────────────────────────
  // Test 1: A → B basic delivery
  // ────────────────────────────────────────────────────────────
  console.log(`${c.bold}[Test 1] Cross-instance delivery: Client A → Client B${c.reset}`);
  try {
    const msg1 = 'Hello from Instance A!';
    const updateBytes = makeTextUpdate(msg1);

    console.log(`  Sending "${msg1}" (${updateBytes.length} bytes) via server:1…`);

    const { latencyMs, receivedUpdateBytes } = await sendAndAwaitRelay(
      clientA_socket, clientB_socket, DOC_ID, updateBytes
    );
    const receivedText = applyAndRead(ydocB, receivedUpdateBytes);

    const latencyLabel = latencyMs > LATENCY_WARN_MS
      ? `${c.yellow}${latencyMs}ms${c.reset}`
      : `${c.green}${latencyMs}ms${c.reset}`;

    if (receivedText.includes(msg1)) {
      console.log(`  ${pass} Received at Client B via server:2 in ${latencyLabel}`);
      console.log(`  ${pass} Content verified: "${receivedText}"`);
      results.push({ name: 'T1 A→B basic delivery', pass: true, latencyMs });
    } else {
      console.log(`  ${fail} Content mismatch — got: "${receivedText}"`);
      results.push({ name: 'T1 A→B basic delivery', pass: false });
    }
  } catch (err) {
    console.log(`  ${fail} ${c.red}${err.message}${c.reset}`);
    results.push({ name: 'T1 A→B basic delivery', pass: false, error: err.message });
  }
  console.log('');

  // ────────────────────────────────────────────────────────────
  // Test 2: B → A bidirectional
  // ────────────────────────────────────────────────────────────
  console.log(`${c.bold}[Test 2] Bidirectional: Client B → Client A${c.reset}`);
  try {
    const msg2 = 'Reply from Instance B!';
    const updateBytes = makeTextUpdate(msg2);

    console.log(`  Sending "${msg2}" (${updateBytes.length} bytes) via server:2…`);

    const { latencyMs, receivedUpdateBytes } = await sendAndAwaitRelay(
      clientB_socket, clientA_socket, DOC_ID, updateBytes
    );
    const receivedText = applyAndRead(ydocA, receivedUpdateBytes);

    const latencyLabel = latencyMs > LATENCY_WARN_MS
      ? `${c.yellow}${latencyMs}ms${c.reset}`
      : `${c.green}${latencyMs}ms${c.reset}`;

    if (receivedText.includes(msg2)) {
      console.log(`  ${pass} Received at Client A via server:1 in ${latencyLabel}`);
      console.log(`  ${pass} Content verified: "${receivedText}"`);
      results.push({ name: 'T2 B→A bidirectional', pass: true, latencyMs });
    } else {
      console.log(`  ${fail} Content mismatch — got: "${receivedText}"`);
      results.push({ name: 'T2 B→A bidirectional', pass: false });
    }
  } catch (err) {
    console.log(`  ${fail} ${c.red}${err.message}${c.reset}`);
    results.push({ name: 'T2 B→A bidirectional', pass: false, error: err.message });
  }
  console.log('');

  // ────────────────────────────────────────────────────────────
  // Test 3: Rapid-fire — no dropped updates
  // ────────────────────────────────────────────────────────────
  console.log(`${c.bold}[Test 3] Rapid-fire: ${RAPID_UPDATE_COUNT} updates A→B, no drops${c.reset}`);
  try {
    let receivedCount = 0;
    const latencies = [];

    // Register the listener BEFORE sending any updates.
    const receivePromise = new Promise((resolve, reject) => {
      const timeout = setTimeout(() => {
        reject(new Error(
          `Only ${receivedCount}/${RAPID_UPDATE_COUNT} updates received before timeout`
        ));
      }, 10_000);

      clientB_socket.on('doc:update', function handler() {
        receivedCount++;
        latencies.push(Date.now() - batchT0);
        if (receivedCount === RAPID_UPDATE_COUNT) {
          clientB_socket.off('doc:update', handler);
          clearTimeout(timeout);
          resolve();
        }
      });
    });

    let batchT0 = Date.now();
    for (let i = 0; i < RAPID_UPDATE_COUNT; i++) {
      const updateBytes = makeTextUpdate(`update-${String(i).padStart(3, '0')}`);
      clientA_socket.emit('doc:update', { docId: DOC_ID, update: Buffer.from(updateBytes) });
    }

    await receivePromise;
    const avgMs = Math.round(latencies.reduce((a, b) => a + b, 0) / latencies.length);

    console.log(`  ${pass} All ${RAPID_UPDATE_COUNT}/${RAPID_UPDATE_COUNT} updates received`);
    console.log(`  ${pass} Average delivery: ${c.green}${avgMs}ms${c.reset}`);
    results.push({ name: `T3 ${RAPID_UPDATE_COUNT} rapid updates`, pass: true, latencyMs: avgMs });
  } catch (err) {
    console.log(`  ${fail} ${c.red}${err.message}${c.reset}`);
    results.push({ name: `T3 ${RAPID_UPDATE_COUNT} rapid updates`, pass: false, error: err.message });
  }
  console.log('');

  // ────────────────────────────────────────────────────────────
  // Test 4: Latency statistics
  // ────────────────────────────────────────────────────────────
  console.log(`${c.bold}[Test 4] Latency stats over ${LATENCY_SAMPLE_COUNT} samples${c.reset}`);
  try {
    const latencies = [];

    for (let i = 0; i < LATENCY_SAMPLE_COUNT; i++) {
      const updateBytes = makeTextUpdate(`sample-${i}`);
      const { latencyMs } = await sendAndAwaitRelay(
        clientA_socket, clientB_socket, DOC_ID, updateBytes
      );
      latencies.push(latencyMs);
    }

    const sorted = [...latencies].sort((a, b) => a - b);
    const p50 = percentile(sorted, 50);
    const p95 = percentile(sorted, 95);
    const max = sorted[sorted.length - 1];
    const min = sorted[0];

    const p95Label = p95 > LATENCY_FAIL_MS
      ? `${c.red}${p95}ms (ABOVE ${LATENCY_FAIL_MS}ms threshold)${c.reset}`
      : `${c.green}${p95}ms${c.reset}`;

    console.log(`  ${pass} ${LATENCY_SAMPLE_COUNT} samples collected`);
    console.log(`       min:  ${c.green}${min}ms${c.reset}`);
    console.log(`       p50:  ${c.green}${p50}ms${c.reset}`);
    console.log(`       p95:  ${p95Label}`);
    console.log(`       max:  ${max > LATENCY_WARN_MS ? c.yellow : c.green}${max}ms${c.reset}`);

    const passed = p95 <= LATENCY_FAIL_MS;
    results.push({ name: `T4 latency p95 ≤ ${LATENCY_FAIL_MS}ms`, pass: passed, latencyMs: p95 });
    if (!passed) {
      console.log(`  ${fail} p95 ${p95}ms exceeds ${LATENCY_FAIL_MS}ms threshold`);
    }
  } catch (err) {
    console.log(`  ${fail} ${c.red}${err.message}${c.reset}`);
    results.push({ name: 'T4 latency stats', pass: false, error: err.message });
  }
  console.log('');

  // ────────────────────────────────────────────────────────────
  // Summary
  // ────────────────────────────────────────────────────────────
  console.log(`${c.bold}═══════════════════════════════════════${c.reset}`);
  console.log(`${c.bold}  RESULTS${c.reset}`);
  console.log(`${c.bold}═══════════════════════════════════════${c.reset}`);

  let allPassed = true;
  for (const r of results) {
    const icon = r.pass ? pass : fail;
    const latency = r.latencyMs != null ? `  ${c.dim}(${r.latencyMs}ms)${c.reset}` : '';
    console.log(`  ${icon} ${r.name}${latency}`);
    if (!r.pass) {
      allPassed = false;
      if (r.error) console.log(`     ${c.red}${r.error}${c.reset}`);
    }
  }

  console.log('');
  if (allPassed) {
    console.log(`${c.bold}${c.green}  ✓ ALL TESTS PASSED — Redis pub/sub is working correctly.${c.reset}`);
    console.log(`${c.dim}  Edits on server:1 reach clients on server:2 via Redis, not direct connection.${c.reset}\n`);
  } else {
    console.log(`${c.bold}${c.red}  ✗ SOME TESTS FAILED${c.reset}`);
    console.log(`${c.dim}  Check that docker compose services are all healthy:${c.reset}`);
    console.log(`${c.dim}  docker compose ps${c.reset}\n`);
  }

  clientA_socket.close();
  clientB_socket.close();
  process.exit(allPassed ? 0 : 1);
}

// ─────────────────────────────────────────────────────────────
// Entry point
// ─────────────────────────────────────────────────────────────

runTests().catch((err) => {
  console.error(`\nFatal error: ${err.message}`);
  process.exit(1);
});
