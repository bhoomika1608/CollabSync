/**
 * gen-yjs-update.js — Generate a minimal valid Yjs binary update for use in k6.
 *
 * WHY pre-generate instead of generating inside k6?
 * k6 runs in a Goja JS runtime that doesn't have Node.js builtins or npm packages.
 * We use Node.js + the real yjs package to produce binary-correct updates, then
 * hardcode them in the k6 script as a static array.
 *
 * Each clientId produces a unique update (different binary representation).
 * We generate 10 updates (clientIds 1-10) so k6 VUs can rotate through them,
 * reducing Yjs deduplication on the server and creating realistic edit traffic.
 */

'use strict';

const Y = require('yjs');

const TEXT_KEY = 'content';

// Generate one Yjs update: a Y.Doc with a single Y.Text insert.
// The update uniqueness comes from the Y.Doc's random clientId.
function makeUpdate(text, clientId) {
  const doc = new Y.Doc({ clientID: clientId });
  doc.getText(TEXT_KEY).insert(0, text);
  const update = Y.encodeStateAsUpdate(doc);
  return Array.from(update);
}

// Awareness update payload (sent as a JSON string inside the Socket.io event).
// Cursor position is a numeric timestamp — server broadcasts it back to all clients.
function makeAwarenessPayload(docId, vuId) {
  return JSON.stringify({
    docId,
    state: {
      user: { name: `k6-vu-${vuId}`, color: '#3498db' },
      cursor: { anchor: Date.now(), head: Date.now() },
    },
  });
}

// --- Print the generated updates as a JS array literal for copy-paste into k6 ---
console.log('// Auto-generated by gen-yjs-update.js');
console.log('// Yjs v1 binary updates for 10 unique clientIds');
console.log('const YJS_UPDATES = [');

for (let i = 1; i <= 10; i++) {
  const bytes = makeUpdate(`edit-${i}`, i * 1000); // clientIds: 1000, 2000, …, 10000
  console.log(`  ${JSON.stringify(bytes)}, // clientId=${i * 1000}`);
}

console.log('];');
console.log('');
console.log(`// Each update is ${makeUpdate('x', 1).length} bytes`);
console.log('// Usage in k6: const update = YJS_UPDATES[__VU % YJS_UPDATES.length];');
